// ============================================================================
// Generated by N64Recomp into src/game/generated/lookup.cpp
// ============================================================================
extern gpr get_entrypoint_address();
extern const char* get_rom_name();

// Global SDL window pointer used by gfx callbacks (declared before use).
static SDL_Window* g_sdl_window = nullptr;

// ============================================================================
// Game entrypoint wrapper
//   recomp::GameEntry expects: void entrypoint(uint8_t* rdram, recomp_context* ctx)
//   N64Recomp generates recomp_func_t functions; we look up the IPL3 entrypoint
//   by VRAM (0x80000400 for N64) and call it.
// ============================================================================
static void wpj2_entrypoint(uint8_t* rdram, recomp_context* ctx) {
    // VRAM 0x80000400 is the N64 IPL3 boot entrypoint.
    // LOOKUP_FUNC casts to int32_t internally, so passing the literal works.
    recomp_func_t* func = LOOKUP_FUNC(0x80000400);
    if (func == nullptr) {
        fprintf(stderr, "[WPJ2] FATAL: entrypoint function at 0x80000400 not found\n");
        ULTRAMODERN_QUICK_EXIT();
    }
    func(rdram, ctx);
}

// ============================================================================
// gfx_callbacks — minimal (window already created by main, just pump SDL)
// ============================================================================
struct Wpj2GfxData {
    SDL_Window* window;
};

void* wpj2_gfx_create_gfx(void) {
    return new Wpj2GfxData{nullptr};
}

ultramodern::renderer::WindowHandle wpj2_gfx_create_window(void* gfx_data) {
    // Window is created in main() before recomp::start; we just need to
    // return it. The gfx_data pointer carries our SDL_Window* via a global.
    auto* data = static_cast<Wpj2GfxData*>(gfx_data);
    data->window = g_sdl_window;
    return g_sdl_window;
}

void wpj2_gfx_update_gfx(void* gfx_data) {
    (void)gfx_data;
    // SDL_PumpEvents already called in input_poll; nothing else to do here.
    // We could process SDL events here, but recomp::start already loops on
    // exited flag — let's poll quit events to allow user to close window.
    SDL_Event event;
    while (SDL_PollEvent(&event)) {
        if (event.type == SDL_QUIT) {
            ultramodern::quit();
        }
    }
}

// ============================================================================
// Event / thread / error callbacks
// ============================================================================
void wpj2_vi_callback(void) {}
void wpj2_gfx_init_callback(void) {}

std::string wpj2_get_game_thread_name(const OSThread* t) {
    (void)t;
    return "GameThread";
}

void wpj2_message_box(const char* msg) {
    SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_ERROR, "WPJ2 Recomp Error", msg, nullptr);
}

// ============================================================================
// Main
// ============================================================================
int main(int argc, char** argv) {
    (void)argc;
    (void)argv;

    printf("=== WPJ2 Recomp Starting ===\n");
    printf("ROM: %s\n", get_rom_name());
    printf("Entry point: 0x%08lX\n", (unsigned long)get_entrypoint_address());

    // ---- 1. SDL2 init ----
    // On Wayland sessions, SDL2 may default to X11 (via XWayland) which causes
    // Vulkan surface creation to fail (missing VK_KHR_wayland_surface extension).
    // Force SDL2 to try Wayland first, then fall back to X11.
    SDL_SetHint(SDL_HINT_VIDEODRIVER, "wayland,x11");
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_JOYSTICK | SDL_INIT_GAMECONTROLLER | SDL_INIT_AUDIO) < 0) {
        fprintf(stderr, "SDL_Init failed: %s\n", SDL_GetError());
        return EXIT_FAILURE;
    }

    // ---- 2. Create window ----
    // WPJ2 native resolution is 320×240 (NTSC, non-interlaced).
    // We start at 2x integer scaling (640×480) and let the user resize.
    // The RT64 renderer will automatically scale the framebuffer to fill
    // the window. Integer scaling is enforced by the window size hint below.
    constexpr int NATIVE_W = 320;
    constexpr int NATIVE_H = 240;
    constexpr int INITIAL_SCALE = 2;  // 640×480

    // NOTE: SDL_WINDOW_VULKAN requires a Vulkan-capable display driver. On
    // headless CI / smoke-test runs (SDL_VIDEODRIVER=dummy/offscreen), that
    // flag fails. We try Vulkan first; if it fails, retry without it so the
    // boot path can still be exercised.
    Uint32 window_flags = SDL_WINDOW_VULKAN | SDL_WINDOW_RESIZABLE;
    g_sdl_window = SDL_CreateWindow(
        "Wonder Project J2 - Recompiled",
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        NATIVE_W * INITIAL_SCALE, NATIVE_H * INITIAL_SCALE,
        window_flags
    );
    if (!g_sdl_window) {
        fprintf(stderr, "[WPJ2] SDL_CreateWindow(Vulkan) failed: %s — retrying without Vulkan flag\n", SDL_GetError());
        window_flags = SDL_WINDOW_RESIZABLE;
        g_sdl_window = SDL_CreateWindow(
            "Wonder Project J2 - Recompiled",
            SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
            NATIVE_W * INITIAL_SCALE, NATIVE_H * INITIAL_SCALE,
            window_flags
        );
    }
    if (!g_sdl_window) {
        fprintf(stderr, "SDL_CreateWindow failed: %s\n", SDL_GetError());
        SDL_Quit();
        return EXIT_FAILURE;
    }

    // Set minimum window size to 1x native (320×240) so the game is always
    // at least visible. The window can be resized to any size; RT64 will
    // stretch the framebuffer to fill it.
    SDL_SetWindowMinimumSize(g_sdl_window, NATIVE_W, NATIVE_H);

    fprintf(stderr, "[WPJ2] Native resolution: %dx%d, initial window: %dx%d (2x)\n",
            NATIVE_W, NATIVE_H, NATIVE_W * INITIAL_SCALE, NATIVE_H * INITIAL_SCALE);

    // ---- 3. Register the game with librecomp ----
    // ROM hash (XXH3_64) — pre-computed for input/wpj2.j1.z64
    // Verified with libxxhash: XXH3_64bits(rom, 8MiB) = 0x068094CAA8D79C24
    constexpr uint64_t WPJ2_ROM_HASH = 0x068094CAA8D79C24ULL;

    recomp::GameEntry entry{};
    entry.rom_hash           = WPJ2_ROM_HASH;
    entry.internal_name      = "Wonder Project J2";
    entry.game_id            = u8"wpj2_jp";
    entry.mod_game_id        = "wpj2";
    entry.save_type          = recomp::SaveType::AllowAll; // CPK via librecomp pak impl
    entry.is_enabled         = true;
    entry.decompression_routine = nullptr;
    entry.has_compressed_code   = false;
    // N64 entrypoint is at virtual address 0x80000400. gpr is uint64_t but
    // the recomp runtime treats addresses as kseg0 sign-extended from int32,
    // so we must cast through int32_t to get the correct 0xFFFFFFFF80000400
    // representation. Otherwise MEM_B/TO_PTR compute wrong offsets.
    entry.entrypoint_address   = (gpr)(int64_t)(int32_t)0x80000400;
    entry.entrypoint           = wpj2_entrypoint;
    entry.thread_create_callback = nullptr;
    entry.on_init_callback      = nullptr;

    if (!recomp::register_game(entry)) {
        fprintf(stderr, "recomp::register_game failed\n");
        SDL_DestroyWindow(g_sdl_window);
        SDL_Quit();
        return EXIT_FAILURE;
    }

    // Set up the config path (where librecomp stores the ROM copy + saves).
    // Default: ~/.config/wpj2-recomp/
    std::filesystem::path config_dir = std::filesystem::path(getenv("HOME")) / ".config" / "wpj2-recomp";
    std::filesystem::create_directories(config_dir);
    recomp::register_config_path(config_dir);

    // Copy ROM into the config path so librecomp can find it (one-time).
    // librecomp looks for "<config_path>/<game_id>.z64".
    std::filesystem::path stored_rom = config_dir / "wpj2_jp.z64";
    if (!std::filesystem::exists(stored_rom)) {
        std::filesystem::path src_rom = std::filesystem::current_path() / "input" / "wpj2.j1.z64";
        if (!std::filesystem::exists(src_rom)) {
            // Try absolute path relative to executable
            src_rom = "/home/marcelo/projects/WPJ2-recomp/input/wpj2.j1.z64";
        }
        if (std::filesystem::exists(src_rom)) {
            std::error_code ec;
            std::filesystem::copy_file(src_rom, stored_rom, ec);
            if (ec) {
                fprintf(stderr, "[WPJ2] Warning: could not copy ROM to %s: %s\n",
                        stored_rom.c_str(), ec.message().c_str());
            } else {
                fprintf(stderr, "[WPJ2] Copied ROM to %s\n", stored_rom.c_str());
            }
        } else {
            fprintf(stderr, "[WPJ2] Warning: ROM not found at %s\n", src_rom.c_str());
        }
    }

    // ---- 4. Build the configuration and start recomp ----
    recomp::Configuration cfg{};
    cfg.project_version = recomp::Version{0, 1, 0, ""};
    cfg.window_handle   = g_sdl_window; // ultramodern's WindowHandle is SDL_Window* on Linux

    // RSP microcode dispatcher
    cfg.rsp_callbacks.get_rsp_microcode = wpj2::get_rsp_microcode;

    // Renderer (RT64 — currently stubbed, real RT64 in Phase 6)
    cfg.renderer_callbacks.create_render_context = wpj2::create_rt64_render_context;

    // Audio (SDL2 queue-based)
    cfg.audio_callbacks.set_frequency      = wpj2::audio_set_frequency;
    cfg.audio_callbacks.queue_samples      = wpj2::audio_queue_samples;
    cfg.audio_callbacks.get_frames_remaining = wpj2::audio_get_frames_remaining;

    // Input
    cfg.input_callbacks.poll_input               = wpj2::input_poll;
    cfg.input_callbacks.get_input                = wpj2::input_get;
    cfg.input_callbacks.set_rumble               = wpj2::input_set_rumble;
    cfg.input_callbacks.get_connected_device_info = wpj2::input_get_connected_device_info;

    // gfx callbacks (window already created; just pump events)
    cfg.gfx_callbacks.create_gfx    = wpj2_gfx_create_gfx;
    cfg.gfx_callbacks.create_window = wpj2_gfx_create_window;
    cfg.gfx_callbacks.update_gfx    = wpj2_gfx_update_gfx;

    // Events
    cfg.events_callbacks.vi_callback       = wpj2_vi_callback;
    cfg.events_callbacks.gfx_init_callback = wpj2_gfx_init_callback;

    // Error handling
    cfg.error_handling_callbacks.message_box = wpj2_message_box;

    // Threads
    cfg.threads_callbacks.get_game_thread_name = wpj2_get_game_thread_name;

    // Message queue control — defaults are correct for WPJ2
    cfg.message_queue_control = ultramodern::MessageQueueControl{};

    // ---- 5. Mark the game as started so the game thread proceeds ----
    recomp::start_game(u8"wpj2_jp");

    // ---- 6. recomp::start blocks until quit ----
    recomp::start(cfg);

    // ---- 7. Cleanup ----
    SDL_DestroyWindow(g_sdl_window);
    SDL_Quit();

    return EXIT_SUCCESS;
}
