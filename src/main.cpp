ultramodern::input::connected_device_info_t ultramodern_get_connected_device_info(int controller_num) {
    if (controller_num < 0 || controller_num >= 4) {
        return {ultramodern::input::Device::None, ultramodern::input::Pak::None};
    }
    // WPJ2 uses Controller Pak (MPK) for saves — but ultramodern's input::Pak
    // doesn't expose ControllerPak as a value yet, so we report None here.
    // Save system is wired separately via librecomp's MPK implementation.
    return {ultramodern::input::Device::Controller, ultramodern::input::Pak::None};
}

