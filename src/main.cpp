/*
 * WPJ2 Recomp - Main Entry Point
 *
 * Wires up N64ModernRuntime + librecomp + RT64 + SDL2.
 *
 * Architecture:
 *   1. SDL2 init + window creation (Vulkan-ready).
 *   2. Register the WPJ2 game entry with librecomp (rom hash, entrypoint fn).
 *   3. Set up all ultramodern callbacks (renderer, audio, input, rsp, ...).
 *   4. Call recomp::start(cfg) — this spawns the game thread, allocates RDRAM,
 *      and blocks until the user quits.
 *
 * The recomp::start path is the official integration pattern. It internally:
 *   - Allocates RDRAM via mmap with guard pages
 *   - Calls ultramodern::preinit(rdram, window_handle)
 *   - Spawns the game thread which calls our registered entrypoint
 *   - Pumps gfx_callbacks.update_gfx on the main thread until quit
 *
 * Entrypoint function pointer:
 *   The recompiled entrypoint is generated by N64Recomp into
 *   src/game/generated/lookup.cpp as `get_function(0x80000400)`.
 *   We expose a thin wrapper that LOOKUP_FUNCs and calls it.
 */

