bool ultramodern_get_input(int controller_num, uint16_t* buttons, float* x, float* y) {
    if (controller_num < 0 || controller_num >= 4) return false;

    // Keyboard fallback (P1 only)
    if (controller_num == 0) {
        const Uint8* kb = SDL_GetKeyboardState(nullptr);
        uint16_t b = 0;
        if (kb[SDL_SCANCODE_RETURN] || kb[SDL_SCANCODE_SPACE]) b |= 0x8000; // A
        if (kb[SDL_SCANCODE_LSHIFT])                              b |= 0x4000; // B
        if (kb[SDL_SCANCODE_Z])                                   b |= 0x2000; // Z
        if (kb[SDL_SCANCODE_X])                                   b |= 0x1000; // Start
        if (kb[SDL_SCANCODE_UP]    || kb[SDL_SCANCODE_W]) b |= 0x0800;
        if (kb[SDL_SCANCODE_DOWN]  || kb[SDL_SCANCODE_S]) b |= 0x0400;
        if (kb[SDL_SCANCODE_LEFT]  || kb[SDL_SCANCODE_A]) b |= 0x0200;
        if (kb[SDL_SCANCODE_RIGHT] || kb[SDL_SCANCODE_D]) b |= 0x0100;
        *buttons = b;
        *x = 0.0f;
        *y = 0.0f;
        return true;
    }

    *buttons = 0;
    *x = 0.0f;
    *y = 0.0f;
    return true;
}

