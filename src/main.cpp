// ============================================================================
// Main entry point
// ============================================================================
int main(int argc, char** argv) {
    (void)argc;
    (void)argv;

    printf("=== WPJ2 Recomp Starting ===\n");
    printf("ROM: %s\n", get_rom_name());
    printf("Entry point: 0x%08lX\n", (unsigned long)get_entrypoint_address());

    // Allocate RDRAM (8 MiB) — must exist BEFORE preinit() because
    // ultramodern functions now take RDRAM_ARG.
    static uint8_t* rdram = nullptr;
    rdram = static_cast<uint8_t*>(aligned_alloc(0x1000, 8 * 1024 * 1024));
    if (!rdram) {
        fprintf(stderr, "Failed to allocate RDRAM\n");
        return EXIT_FAILURE;
    }
    memset(rdram, 0, 8 * 1024 * 1024);

    // Initialize SDL2 (no SDL3 — use JOYSTICK, not GAMEPAD)
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_JOYSTICK | SDL_INIT_GAMECONTROLLER | SDL_INIT_AUDIO) < 0) {
        fprintf(stderr, "Failed to initialize SDL: %s\n", SDL_GetError());
        free(rdram);
        return EXIT_FAILURE;
    }

    SDL_Window* window = SDL_CreateWindow(
        "Wonder Project J2 - Recompiled",
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        640, 480,
        SDL_WINDOW_VULKAN | SDL_WINDOW_RESIZABLE
    );
    if (!window) {
        fprintf(stderr, "Failed to create window: %s\n", SDL_GetError());
        SDL_Quit();
        free(rdram);
        return EXIT_FAILURE;
    }

    // Register all ultramodern callbacks BEFORE preinit()
    ultramodern::rsp::callbacks_t rsp_cb{};
    rsp_cb.init     = ultramodern_rsp_init;
    rsp_cb.run_task = ultramodern_rsp_run_task;

    ultramodern::renderer::callbacks_t renderer_cb{};
    renderer_cb.create_render_context = ultramodern::renderer::create_rt64_render_context;

    ultramodern::audio_callbacks_t audio_cb{};
    audio_cb.set_frequency      = ultramodern_audio_set_frequency;
    audio_cb.queue_samples      = ultramodern_audio_queue_samples;
    audio_cb.get_frames_remaining = ultramodern_audio_get_frames_remaining;

    ultramodern::input::callbacks_t input_cb{};
    input_cb.poll_input               = ultramodern_poll_input;
    input_cb.get_input                = ultramodern_get_input;
    input_cb.set_rumble               = ultramodern_set_rumble;
    input_cb.get_connected_device_info = ultramodern_get_connected_device_info;

    ultramodern::gfx_callbacks_t gfx_cb{};
    gfx_cb.create_gfx    = ultramodern_gfx_create_gfx;
    gfx_cb.create_window = ultramodern_gfx_create_window;
    gfx_cb.update_gfx    = ultramodern_gfx_update_gfx;

    ultramodern::events::callbacks_t events_cb{};
    events_cb.vi_callback        = ultramodern_vi_callback;
    events_cb.gfx_init_callback  = ultramodern_gfx_init_callback;

    ultramodern::error_handling::callbacks_t error_cb{};
    error_cb.message_box = ultramodern_message_box;

    ultramodern::threads::callbacks_t threads_cb{};
    threads_cb.get_game_thread_name = ultramodern_get_game_thread_name;

    ultramodern::set_callbacks(
        rsp_cb, renderer_cb, audio_cb, input_cb,
        gfx_cb, events_cb, error_cb, threads_cb
    );

    // Initialize ultramodern (preinit internally calls init_events/init_timers/init_audio/init_thread_cleanup).
    ultramodern::preinit(rdram, window);
    ultramodern::init_saving(rdram);

    // Mark this thread as entrypoint
    ultramodern::set_entrypoint_thread();

    printf("Starting game...\n");

    // Look up the recompiled entry point (0x80000400 for N64 IPL3 boot).
    recomp_func_t* entry_func = LOOKUP_FUNC(0x80000400);
    if (!entry_func) {
        fprintf(stderr, "Failed to find entry point function at 0x80000400\n");
        SDL_DestroyWindow(window);
        SDL_Quit();
        free(rdram);
        return EXIT_FAILURE;
    }

    // Create recomp context and call entry point.
    recomp_context ctx{};
    ctx.mips3_float_mode = 1;
    entry_func(rdram, &ctx);

    // Main scheduler loop. The recompiled entry point yields, and we keep
    // pumping the ultramodern scheduler + SDL events until the user quits.
    bool quit = false;
    while (!quit) {
        ultramodern::run_next_thread_and_wait(rdram);

        SDL_Event event;
        while (SDL_PollEvent(&event)) {
            if (event.type == SDL_QUIT) {
                quit = true;
                break;
            }
        }
    }

    // Cleanup
    ultramodern::join_event_threads();
    ultramodern::join_thread_cleaner_thread();
    ultramodern::join_saving_thread();

    SDL_DestroyWindow(window);
    SDL_Quit();
    free(rdram);

    return EXIT_SUCCESS;
}
