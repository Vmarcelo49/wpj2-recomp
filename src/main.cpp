// Global SDL window pointer used by gfx callbacks (declared before use).
static SDL_Window* g_sdl_window = nullptr;
static bool g_fullscreen = false;

// ---------------------------------------------------------------------------
// Build variant selection.
//
// The Japanese and English builds use different recompiled CPU code and
// different ROMs.  Each build gets its own game id, so their ROM copies and
// save data cannot be mixed in a shared config directory.
// ---------------------------------------------------------------------------
#if defined(WPJ2_ENGLISH_BUILD)
static constexpr const char* WPJ2_VARIANT_NAME = "en";
static constexpr uint64_t WPJ2_DEFAULT_ROM_HASH = 0xEDF6BD1A8E68B1DCULL; // canonical verified EN image (english.z64)
static constexpr const char8_t* WPJ2_VARIANT_GAME_ID = u8"wpj2_en";
static constexpr const char* WPJ2_DEFAULT_ROM_FILE = "wpj2.en.z64";
#else
static constexpr const char* WPJ2_VARIANT_NAME = "jp";
static constexpr uint64_t WPJ2_DEFAULT_ROM_HASH = 0x068094CAA8D79C24ULL; // verified original JP ROM
static constexpr const char8_t* WPJ2_VARIANT_GAME_ID = u8"wpj2_jp";
static constexpr const char* WPJ2_DEFAULT_ROM_FILE = "wpj2.j1.z64";
#endif

// ============================================================================
// Game entrypoint wrapper
//   recomp::GameEntry expects: void entrypoint(uint8_t* rdram, recomp_context* ctx)
//   N64Recomp generates recomp_func_t functions; we look up the IPL3 entrypoint
//   by VRAM (0x80000400 for N64) and call it.
// ============================================================================
static void wpj2_entrypoint(uint8_t* rdram, recomp_context* ctx) {
    // VRAM 0x80000400 is the N64 IPL3 boot entrypoint.
    // LOOKUP_FUNC casts to int32_t internally, so passing the literal works.
    recomp_func_t* func = LOOKUP_FUNC(0x80000400);
    if (func == nullptr) {
        fprintf(stderr, "[WPJ2] FATAL: entrypoint function at 0x80000400 not found\n");
        ULTRAMODERN_QUICK_EXIT();
    }
    func(rdram, ctx);
}

// ============================================================================
// gfx_callbacks — minimal (window already created by main, just pump SDL)
// ============================================================================
struct Wpj2GfxData {
    SDL_Window* window;
};

void* wpj2_gfx_create_gfx(void) {
    return new Wpj2GfxData{nullptr};
}

ultramodern::renderer::WindowHandle wpj2_gfx_create_window(void* gfx_data) {
    // Window is created in main() before recomp::start; we just need to
    // return it. The gfx_data pointer carries our SDL_Window* via a global.
    auto* data = static_cast<Wpj2GfxData*>(gfx_data);
    data->window = g_sdl_window;
    return g_sdl_window;
}

void wpj2_gfx_update_gfx(void* gfx_data) {
    (void)gfx_data;
    // Poll SDL events: quit, key presses for scaling toggle, etc.
    SDL_Event event;
    while (SDL_PollEvent(&event)) {
        if (event.type == SDL_QUIT) {
            ultramodern::quit();
        }
        else if (event.type == SDL_KEYDOWN) {
            switch (event.key.keysym.scancode) {
                case SDL_SCANCODE_F9:
                    // F9 avoids conflicting with the S/D-pad-down game input.
                    wpj2::toggle_renderer_scaling();
                    break;
                case SDL_SCANCODE_F11:
                    // Toggle fullscreen
                    {
                        g_fullscreen = !g_fullscreen;
                        SDL_SetWindowFullscreen(g_sdl_window,
                            g_fullscreen ? SDL_WINDOW_FULLSCREEN_DESKTOP : 0);
                        fprintf(stderr, "[WPJ2] Fullscreen: %s\n", g_fullscreen ? "ON" : "OFF");
                    }
                    break;
                default:
                    break;
            }
        }
    }
}

