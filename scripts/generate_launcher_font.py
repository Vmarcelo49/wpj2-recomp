#!/usr/bin/env python3
"""Bake an antialiased SIL OFL font into a C++ header for the launcher.

The launcher has no runtime text-rendering dependency. This tool rasterizes
printable ASCII into 8-bit alpha bitmaps that are compiled into
wpj2-launcher and drawn through an SDL texture with linear filtering.

Usage:
    python3 scripts/generate_launcher_font.py \
        --font resources/fonts/Roboto.ttf \
        --output src/launcher/embedded_font.hpp

Requires Pillow. The generated header is checked in, so Pillow is only needed
when regenerating it.
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CELL_W = 24
CELL_H = 24
PAD = 2
FONT_SIZE = 18
FIRST_CHAR = 32
LAST_CHAR = 126


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path,
                        default=Path("resources/fonts/Roboto.ttf"))
    parser.add_argument("--output", type=Path,
                        default=Path("src/launcher/embedded_font.hpp"))
    args = parser.parse_args()

    font = ImageFont.truetype(str(args.font), FONT_SIZE)
    try:
        font.set_variation_by_name("Regular")
    except OSError:
        pass
    ascent, _descent = font.getmetrics()

    lines = [
        "// Generated by scripts/generate_launcher_font.py. Do not edit.",
        "// Source: Roboto by Google, SIL OFL 1.1.",
        "#ifndef WPJ2_EMBEDDED_FONT_HPP",
        "#define WPJ2_EMBEDDED_FONT_HPP",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace wpj2_launcher::font {",
        "",
        f"constexpr int cell_width = {CELL_W};",
        f"constexpr int cell_height = {CELL_H};",
        f"constexpr int first_char = {FIRST_CHAR};",
        f"constexpr int last_char = {LAST_CHAR};",
        "",
        "struct Glyph {",
        "    std::array<uint8_t, cell_width * cell_height> alpha{};",
        "    int advance = 0;",
        "};",
        "",
        "constexpr std::array<Glyph, last_char - first_char + 1> glyphs = {{",
    ]

    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        char = chr(code)
        image = Image.new("L", (CELL_W, CELL_H), 0)
        draw = ImageDraw.Draw(image)
        draw.text((PAD, PAD + ascent), char, font=font, fill=255, anchor="ls")

        alpha = [image.getpixel((x, y))
                 for y in range(CELL_H) for x in range(CELL_W)]
        alpha_lines = []
        for row in range(CELL_H):
            start = row * CELL_W
            alpha_lines.append(
                "        " + ", ".join(str(v) for v in alpha[start:start + CELL_W]) + ","
            )

        advance = max(1, min(CELL_W, round(font.getlength(char)) + 1))
        if code == ord(" "):
            advance = 7
        lines.append("    Glyph{ {")
        lines.extend(alpha_lines)
        lines.append(f"    }}, {advance} }},")

    lines += [
        "}};",
        "",
        "} // namespace wpj2_launcher::font",
        "",
        "#endif",
        "",
    ]
    args.output.write_text("\n".join(lines))
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
